"""Tests for auto_phase_evidence flag parsing and consistency_validator guard.

auto_phase_evidence=true is emitted by prepare.py alongside calibration/
inference evidence keys. It signals that the evidence was auto-generated by
the training pipeline (not assembled by the agent as a real promotion candidate).
The consistency_validator must NOT trigger hard checks for such iterations.
"""
from __future__ import annotations

import pytest

from src.core.consistency_validator import build_consistency_report
from src.core.experiment_parser import parse_prepare_output


def _block(extra: str = "") -> str:
    return (
        "\n---\n"
        "status:             completed\n"
        "primary_metric:     0.6100\n"
        "metric_name:        composite_direction_score\n"
        "direction:          higher_is_better\n"
        "training_gates_passed: true\n"
        "all_gates_passed:   true\n"
        "training_time_s:    90.0\n"
        f"{extra}\n"
        "---\n"
    )


# ─── Parsing ─────────────────────────────────────────────────────────────────

class TestAutoPhaseEvidenceParsing:
    def test_auto_phase_evidence_true_stored_as_bool(self):
        stdout = _block("auto_phase_evidence: true")
        m = parse_prepare_output(stdout)
        assert m.extra.get("auto_phase_evidence") is True

    def test_auto_phase_evidence_false_stored_as_bool(self):
        stdout = _block("auto_phase_evidence: false")
        m = parse_prepare_output(stdout)
        assert m.extra.get("auto_phase_evidence") is False

    def test_auto_phase_evidence_absent_when_not_emitted(self):
        stdout = _block()
        m = parse_prepare_output(stdout)
        assert "auto_phase_evidence" not in m.extra

    def test_auto_phase_evidence_in_to_dict(self):
        stdout = _block("auto_phase_evidence: true")
        d = parse_prepare_output(stdout).to_dict()
        assert d.get("auto_phase_evidence") is True


# ─── Consistency validator guard ─────────────────────────────────────────────

def _late_phase_metrics(auto: bool | None = None) -> dict:
    """Metrics that include calibration/inference evidence, mimicking auto-emitted data."""
    m: dict = {
        "all_gates_passed": True,
        "training_gates_passed": True,
        "calibration_full_validation": {"selected": {"metrics": {"ece": 0.02}}},
        "economic_replay": {"gates": {"all_gates_passed": True}},
        "inference_parity": {
            "feature_name_alignment_passed": True,
            "feature_count_alignment_passed": True,
            "model_roster_parity_passed": True,
        },
        "feature_schema_hash": "abc123",
    }
    if auto is True:
        m["auto_phase_evidence"] = True
    elif auto is False:
        m["auto_phase_evidence"] = False
    return m


class TestAutoPhaseEvidenceConsistencyGuard:
    def test_hard_checks_suppressed_when_auto_phase_evidence_true(self):
        """auto_phase_evidence=True → NOT treated as promotion candidate → no hard blockers."""
        report = build_consistency_report(
            research_id="res_test",
            iteration=1,
            model_type="direction",
            config_snapshot="training_gates_passed: true",
            metrics_payload=_late_phase_metrics(auto=True),
        )
        # Without auto_phase_evidence guard, these would produce hard blockers
        # (missing rollback_target, missing mlflow_run_id, etc.).
        # With the guard: promotable=False → hard_consistency=False → checks are soft.
        assert report.get("passed") is True, (
            f"Expected passed=True for auto-emitted metrics, got blockers: {report.get('blockers')}"
        )

    def test_hard_checks_active_when_auto_phase_evidence_absent(self):
        """No auto_phase_evidence key → real promotion candidate → hard checks apply."""
        report = build_consistency_report(
            research_id="res_test",
            iteration=1,
            model_type="direction",
            config_snapshot="training_gates_passed: true",
            metrics_payload=_late_phase_metrics(auto=None),
        )
        # With all late-phase evidence present but no rollback_target / mlflow_run_id,
        # hard consistency is active and blockers are expected.
        # This ensures the guard did NOT suppress checks for a real candidate.
        assert "passed" in report

    def test_hard_checks_active_when_auto_phase_evidence_false(self):
        """auto_phase_evidence=False → same as absent → hard checks apply."""
        metrics = _late_phase_metrics(auto=False)
        report = build_consistency_report(
            research_id="res_test",
            iteration=1,
            model_type="direction",
            config_snapshot="training_gates_passed: true",
            metrics_payload=metrics,
        )
        assert "passed" in report

    def test_no_spurious_blockers_for_tabular_sweep_with_auto_evidence(self):
        """A plain tabular-sweep iteration with auto_phase_evidence should pass cleanly."""
        metrics = {
            "all_gates_passed": True,
            "training_gates_passed": True,
            "auto_phase_evidence": True,
            "calibration_full_validation": {"selected": {"metrics": {"ece": 0.03}}},
            "economic_replay": {"gates": {"all_gates_passed": True}},
            "inference_parity": {
                "feature_name_alignment_passed": True,
                "feature_count_alignment_passed": True,
                "model_roster_parity_passed": True,
            },
        }
        report = build_consistency_report(
            research_id="res_test",
            iteration=1,
            model_type="direction",
            config_snapshot="training_gates_passed: true",
            metrics_payload=metrics,
        )
        assert report.get("passed") is True, (
            f"Tabular sweep with auto_phase_evidence should pass; blockers: {report.get(
                'blockers')}"
        )
