"""Shared platform header contracts and utilities."""

from __future__ import annotations

from contextvars import ContextVar
from dataclasses import dataclass
from functools import wraps
from typing import Annotated, Final, Mapping, TypedDict
from uuid import uuid4

from fastapi import APIRouter, Depends, FastAPI, Header
from starlette.requests import HTTPConnection

try:
    from libs.observability.correlation import get_correlation_id
    from libs.observability.tenant import get_tenant_id
except ModuleNotFoundError:
    from .correlation import get_correlation_id
    from .tenant import get_tenant_id

CORRELATION_ID_HEADER: Final[str] = "X-Request-ID"
TENANT_ID_HEADER: Final[str] = "X-Tenant-Id"
API_KEY_HEADER: Final[str] = "X-API-Key"

_HEADER_DENYLIST: Final[set[str]] = {"host"}


class PlatformHeaderSpec(TypedDict):
    """Schema describing platform header semantics."""

    description: str
    behavior: str
    example: str
    required: bool


PLATFORM_HEADER_SPECS: Final[dict[str, PlatformHeaderSpec]] = {
    CORRELATION_ID_HEADER: {
        "description": "Correlation identifier used for distributed tracing across services.",
        "behavior": "Auto-generated UUID4 when missing; caller-provided value is echoed.",
        "example": "3a1c2b44-91ec-4ca9-acf8-6d34307c6e7d",
        "required": False,
    },
    TENANT_ID_HEADER: {
        "description": "Tenant identifier propagated end-to-end for multi-tenant context.",
        "behavior": "Echo-only; never generated by the platform.",
        "example": "tenant-demo",
        "required": False,
    },
    API_KEY_HEADER: {
        "description": (
            "Optional API key for service-to-service authentication when OAuth is unavailable."
        ),
        "behavior": "Forwarded unchanged if provided.",
        "example": "sk_live_example",
        "required": False,
    },
}


def _header_examples(header_name: str) -> dict[str, dict[str, str]]:
    """Return FastAPI-compatible examples payload for platform headers."""

    spec = PLATFORM_HEADER_SPECS[header_name]
    return {
        "default": {
            "summary": spec["behavior"],
            "value": spec["example"],
        }
    }


CorrelationHeaderParam = Annotated[
    str | None,
    Header(
        alias=CORRELATION_ID_HEADER,
        description=PLATFORM_HEADER_SPECS[CORRELATION_ID_HEADER]["description"],
        examples=_header_examples(CORRELATION_ID_HEADER),
    ),
]

TenantHeaderParam = Annotated[
    str | None,
    Header(
        alias=TENANT_ID_HEADER,
        description=PLATFORM_HEADER_SPECS[TENANT_ID_HEADER]["description"],
        examples=_header_examples(TENANT_ID_HEADER),
    ),
]

ApiKeyHeaderParam = Annotated[
    str | None,
    Header(
        alias=API_KEY_HEADER,
        description=PLATFORM_HEADER_SPECS[API_KEY_HEADER]["description"],
        examples=_header_examples(API_KEY_HEADER),
    ),
]


@dataclass(slots=True)
class PlatformHeaders:
    """Normalized representation of incoming platform headers."""

    correlation_id: str | None
    tenant_id: str | None
    api_key: str | None


_platform_headers_var: ContextVar[PlatformHeaders | None] = ContextVar(
    "platform_headers",
    default=None,
)


def get_bound_platform_headers() -> PlatformHeaders | None:
    """Return the PlatformHeaders instance bound to the current request, if any."""

    return _platform_headers_var.get()


def _set_canonical_header(headers: dict[str, str], key: str, value: str) -> None:
    """Ensure only the canonical casing of a header is present before setting it."""
    lower_key = key.lower()
    for existing_key in list(headers.keys()):
        if existing_key.lower() == lower_key and existing_key != key:
            headers.pop(existing_key)
    headers[key] = value


def ensure_platform_headers(
    headers: Mapping[str, str] | None = None,
    *,
    correlation_id: str | None = None,
    tenant_id: str | None = None,
    api_key: str | None = None,
) -> dict[str, str]:
    """Return a sanitized header dict with platform defaults applied.

    Args:
        headers: Incoming headers (case-sensitive keys preserved).
        correlation_id: Optional override; defaults to context value.
        tenant_id: Optional override; defaults to context value.
        api_key: Optional override; defaults to provided headers.

    Returns:
        Dictionary ready to attach to outbound requests.
    """
    sanitized: dict[str, str] = {}
    if headers:
        for name, value in headers.items():
            if name.lower() in _HEADER_DENYLIST:
                continue
            sanitized[name] = value

    if not correlation_id:
        correlation_id = get_correlation_id()
    if correlation_id:
        _set_canonical_header(sanitized, CORRELATION_ID_HEADER, correlation_id)

    if tenant_id is None:
        tenant_id = get_tenant_id()
    if tenant_id:
        _set_canonical_header(sanitized, TENANT_ID_HEADER, tenant_id)

    if api_key is None:
        bound_headers = get_bound_platform_headers()
        if bound_headers is not None:
            api_key = bound_headers.api_key
    if api_key:
        _set_canonical_header(sanitized, API_KEY_HEADER, api_key)

    return sanitized


def _normalize_header_value(value: str | None) -> str | None:
    if value is None:
        return None
    normalized = value.strip()
    return normalized or None


async def get_platform_headers(
    correlation_id: CorrelationHeaderParam = None,
    tenant_id: TenantHeaderParam = None,
    api_key: ApiKeyHeaderParam = None,
) -> PlatformHeaders:
    """FastAPI dependency returning normalized platform header values."""

    resolved_correlation = _normalize_header_value(correlation_id) or get_correlation_id()
    if not resolved_correlation:
        resolved_correlation = str(uuid4())

    return PlatformHeaders(
        correlation_id=resolved_correlation,
        tenant_id=_normalize_header_value(tenant_id),
        api_key=_normalize_header_value(api_key),
    )


_platform_headers_dependency = Depends(get_platform_headers)


async def bind_platform_headers(
    connection: HTTPConnection,
    platform_headers: PlatformHeaders = _platform_headers_dependency,
) -> PlatformHeaders:
    """Attach normalized platform headers to the connection state for downstream consumers."""

    connection.state.platform_headers = platform_headers
    _platform_headers_var.set(platform_headers)
    return platform_headers


def _has_platform_dependency(dependencies: list) -> bool:
    return any(getattr(dep, "dependency", None) is bind_platform_headers for dep in dependencies)


def ensure_router_platform_headers(router: APIRouter) -> APIRouter:
    """Append the platform headers dependency to a router if missing."""

    if not _has_platform_dependency(router.dependencies):
        router.dependencies.append(Depends(bind_platform_headers))
    return router


def ensure_app_platform_headers(app: FastAPI) -> FastAPI:
    """Ensure a FastAPI app enforces platform headers for all routes and mounted routers."""

    if not _has_platform_dependency(app.router.dependencies):
        app.router.dependencies.append(Depends(bind_platform_headers))

    if not getattr(app.state, "_platform_headers_router_hook", False):
        original_include_router = app.include_router

        @wraps(original_include_router)
        def include_router_with_headers(router: APIRouter, *args, **kwargs):
            ensure_router_platform_headers(router)
            return original_include_router(router, *args, **kwargs)

        app.include_router = include_router_with_headers  # type: ignore[assignment]
        app.state._platform_headers_router_hook = True

    return app


async def document_platform_headers(
    correlation_id: CorrelationHeaderParam = None,
    tenant_id: TenantHeaderParam = None,
    api_key: ApiKeyHeaderParam = None,
) -> None:
    """Backward-compatible alias to document platform headers in OpenAPI schemas."""

    await get_platform_headers(
        correlation_id=correlation_id,
        tenant_id=tenant_id,
        api_key=api_key,
    )
    return None
